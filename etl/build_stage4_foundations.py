def extract_jinkui_clauses(text: str, limit: int = 3) -> list[str]:
    """Extract classic Jinkui clause lines (ending in 主之/名曰/云何/法当 etc.) from cleaned page text."""
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    clauses = []
    buf = []
    for line in lines:
        if (
            "倪海厦注" in line
            or (line.startswith("第") and line.endswith("页"))
            or "校排" in line
            or "勤求古" in line
            or line.endswith(("汤方", "散方", "丸方", "煎方"))
            or re.search(r"脉证.*第[一二三四五六七八九十]+$", line)
            or re.search(r"病脉.*第[一二三四五六七八九十]+$", line)
        ):
            if buf:
                clauses.append("".join(buf))
                buf = []
            continue
        if any(marker in line for marker in ("问曰：", "师曰：", "病者", "太阳病", "夫", "湿家", "痉为病", "妇人", "谷瘅")) or re.search(
            r"(主之|名曰|云何|可与|不可|当温|当利)", line
        ):
            if len(line) <= 68 and not re.search(r"(我们|这里|你们|因为|所以|就是|医生|患者)", line):
                buf.append(line)
                if line.endswith(("。", "？", "！", "之")):
                    clauses.append("".join(buf))
                    buf = []
            elif buf:
                clauses.append("".join(buf))
                buf = []
        elif buf:
            clauses.append("".join(buf))
            buf = []
        if len(clauses) >= limit:
            break
    if buf and len(clauses) < limit:
        clauses.append("".join(buf))
    out = []
    for c in clauses:
        if (
            len(c) >= 12
            and not c.endswith("方")
            and not c.startswith(("是君主", "『师曰", "覆花汤"))
            and c not in out
        ):
            out.append(c)
    return out[:limit]


def extract_ni_snippets(pages_map: dict[int, str], tr_map: dict[int, str], page_nums: list[int], tr_nums: list[int]) -> list[dict]:
    """Extract clean, readable Ni Haixia commentary paragraphs citing real Jinkui book & transcript pages."""
    notes = []
    for pg in page_nums:
        if len(notes) >= 3:
            break
        raw = clean_4x(pages_map.get(pg, ""))
        clean_lines = []
        cur = ""
        for line in raw.splitlines():
            l = line.strip()
            if (
                not l
                or "倪海厦注" in l
                or (l.startswith("第") and l.endswith("页"))
                or "群龙无首" in l
                or "勤求古" in l
                or re.search(r"第[一二三四五六七八九十]+$", l)
            ):
                if cur:
                    clean_lines.append(cur)
                    cur = ""
                continue
            cur += l
            if l.endswith(("。", "？", "！")):
                clean_lines.append(cur)
                cur = ""
        if cur:
            clean_lines.append(cur)
        best = [
            s for s in clean_lines
            if 48 <= len(s) <= 260
            and "汤方" not in s
            and "丸方" not in s
            and not s[0] in ("的", "了", "”", "』", "。", "，")
            and not s.startswith(("的，", "了，", "所以然者", "水』", "是『", "不通，"))
            and not s.endswith(("：", "，"))
            and any(w in s for w in ("这个", "就是", "我们", "这里", "张仲景", "如果", "所以", "代表", "方", "脉"))
        ]
        if best:
            notes.append({"page": pg, "source": "倪海厦注金匮要略", "text": best[0]})
    if tr_nums:
        tpg = tr_nums[0]
        tr_raw = tr_map.get(tpg, "").replace("\n", "")
        tr_clean = re.sub(r"（\d+-\d+min\d+）", "", tr_raw).strip()
        sents = [s.strip() for s in re.split(r"(?<=[。！？])", tr_clean) if s.strip()]
        # Skip initial half-sentence if first segment looks truncated
        if len(sents) > 2 and sents[0].startswith(("的", "了", "因为", "所以")):
            sents = sents[1:]
        excerpt = ""
        for s in sents:
            if len(excerpt) + len(s) <= 220:
                excerpt += s
            elif len(excerpt) >= 65:
                break
        if len(excerpt) >= 40:
            notes.append({"page": tpg, "source": "视频同步文稿", "text": excerpt})
    return notes[:4]


def build_jinkui_chapters() -> dict:
    """Build data/jinkui_chapters.json covering all 20 Jinkui chapters in original book order."""
    jk = read_json(DATA / "jinkui_formulas.json")
    jk_pages = {
        row["page"]: row["text"]
        for row in (
            json.loads(line)
            for line in (SOURCES / "ni_jinkui_pages.jsonl").read_text(encoding="utf-8").splitlines()
            if line.strip()
        )
    }
    jk_tr = {
        row["page"]: row["text"]
        for row in (
            json.loads(line)
            for line in (SOURCES / "ni_jinkui_transcript.jsonl").read_text(encoding="utf-8").splitlines()
            if line.strip()
        )
    }

    chapters_order: list[str] = []
    by_chapter: dict[str, list[dict]] = defaultdict(list)
    for row in jk:
        ch = row["chapter"]
        if ch not in by_chapter:
            chapters_order.append(ch)
        by_chapter[ch].append(row)

    assert len(chapters_order) == len(JINKUI_CHAPTER_META) == 20, f"Unexpected chapter count: {len(chapters_order)}"

    items = []
    for idx, ch_name in enumerate(chapters_order, 1):
        meta = JINKUI_CHAPTER_META[idx - 1]
        rows = by_chapter[ch_name]
        fids = [r["id"] for r in rows]
        formula_names = [r["name"] for r in rows]
        src_pages = sorted({r["source"]["page"] for r in rows if r.get("source", {}).get("page")})
        # Anchor strictly from the page where this chapter title begins (avoid bleeding from previous chapter)
        header_pages = [
            p for p in range(max(1, src_pages[0] - 8), src_pages[0] + 1)
            if ch_name[:4] in clean_4x(jk_pages.get(p, ""))
        ]
        ch_start = header_pages[0] if header_pages else src_pages[0]
        scan_pages = sorted(set([ch_start, min(src_pages[-1], ch_start + 1)] + src_pages[:4]))
        clauses: list[str] = []
        for p in scan_pages:
            for cl in extract_jinkui_clauses(clean_4x(jk_pages.get(p, "")), limit=2):
                if cl not in clauses:
                    clauses.append(cl)
            if len(clauses) >= 4:
                break
        if not clauses:
            for r in rows[:3]:
                if r.get("indication"):
                    clauses.append(r["indication"])

        # Find transcript pages mentioning chapter title or first 2 formula names
        tr_pages = sorted(
            {
                p
                for p, txt in jk_tr.items()
                if ch_name[:4] in txt or any(fn in txt for fn in formula_names[:3])
            }
        )[:12]

        # Extract symptoms cleanly from formula indications & chapter clauses
        sym_candidates = []
        symptom_lexicon = [
            "吐利", "恶寒", "发热", "头痛", "身痛", "汗出", "无汗", "项背强", "口噤", "脉沉迟",
            "关节疼痛", "烦疼", "小便不利", "大便反快", "半身不遂", "麻木不仁", "骨节疼", "脉微涩",
            "失精", "虚劳", "短气", "咳唾涎沫", "喘", "胸满", "奔豚", "胸痹", "心痛彻背",
            "腹满", "寒疝", "绕脐痛", "胁下痛", "痰饮", "水气", "消渴", "渴欲饮水", "身黄",
            "惊悸", "吐血", "衄血", "下血", "呕吐", "哕", "下利", "少腹肿痞", "转筋", "狐疝",
            "吐涎", "妊娠腹痛", "胎动", "漏下", "产后腹痛", "郁冒", "大便难", "寒热有时", "经水适断",
            "咽中有炙脔", "悲伤欲哭",
        ]
        combined_text = " ".join(
            [ch_name, meta["category"], *meta["treatment"], *clauses, *(r.get("indication", "") for r in rows[:8])]
        )
        for kw in symptom_lexicon:
            if kw in combined_text and kw not in sym_candidates:
                sym_candidates.append(kw)
        if not sym_candidates:
            sym_candidates = [ch_name.split("病")[0] + "脉证"]

        annotations = extract_ni_snippets(jk_pages, jk_tr, scan_pages, tr_pages)
        summary = (
            f"本篇为《金匮要略》第{idx}顺位编目章节「{ch_name}」，归类为「{meta['category']}」，"
            f"共收录原书经方 {len(fids)} 首（页码涵盖第 {src_pages[0]}–{src_pages[-1]} 页）。"
            f"核心辨证以脉证分类立法，严守原书分篇次序并与《伤寒论》同名方双向互参。"
        )
        items.append(
            {
                "id": f"jk-ch-{idx:02d}",
                "order": idx,
                "name": ch_name,
                "disease_category": meta["category"],
                "status": "reviewed",
                "status_label": "已整理",
                "summary": summary,
                "symptoms": sym_candidates[:10],
                "pulse_and_syndrome": clauses,
                "treatment_principles": meta["treatment"],
                "formula_ids": fids,
                "formula_variations": meta["variations"],
                "differentiation_points": meta["diffs"],
                "annotations": annotations,
                "source_pages": src_pages,
                "transcript_pages": tr_pages,
                "proof_note": f"据《倪海厦注金匮要略》（页{src_pages[0]}–{src_pages[-1]}）及视频同步文稿核对，保留原书篇次与全部{len(fids)}首方剂。",
            }
        )

    payload = {"items": items}
    write_json(DATA / "jinkui_chapters.json", payload)
    return payload


def main() -> int:
    sc = build_six_channels()
    jk = build_jinkui_chapters()
    sc_total = sum(len(item["related_formula_ids"]) for item in sc["items"])
    jk_total = sum(len(item["formula_ids"]) for item in jk["items"])
    print(f"six_channels={len(sc['items'])} (formulas={sc_total}), jinkui_chapters={len(jk['items'])} (formulas={jk_total})")
    return 0


