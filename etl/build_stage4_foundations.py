"""Build complete Stage 4 foundation datasets: six_channels.json (6/6) and jinkui_chapters.json (20/20)."""
from __future__ import annotations

from collections import defaultdict
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "brain_data"
SOURCES = ROOT / "sources"


def read_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, payload) -> None:
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def clean_4x(text: str) -> str:
    """Collapse 4x bold-glyph PDF OCR repetition without altering source files."""
    return re.sub(r"(.)\1{3}", r"\1", text)


def load_shanghan_channel_map() -> tuple[dict[str, list[str]], dict[str, list[int]]]:
    """Return ordered formula IDs and curated page numbers grouped by primary six_channel.id."""
    formulas = read_json(DATA / "formulas.json")
    curated = read_json(DATA / "curated_formulas.json")
    manifest = read_json(DATA / "curated_batch_manifest.json").get("accepted", [])
    merged = dict(curated)
    for batch_name in manifest:
        merged.update(read_json(DATA / "curated_batches" / batch_name))

    by_channel: dict[str, list[str]] = defaultdict(list)
    pages_by_channel: dict[str, set[int]] = defaultdict(set)
    for row in formulas:
        fid = row["id"]
        mod = merged[fid]
        sc_id = (mod.get("six_channel") or {}).get("id") or "taiyang"
        by_channel[sc_id].append(fid)
        for pr in mod.get("page_reading", []):
            pg = pr.get("page")
            if isinstance(pg, int):
                pages_by_channel[sc_id].add(pg)
    return by_channel, {k: sorted(v) for k, v in pages_by_channel.items()}


