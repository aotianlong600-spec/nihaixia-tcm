def read_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, payload) -> None:
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def _ing_map(formula: dict) -> dict[str, dict]:
    out = {}
    for row in formula.get("ingredients", []):
        key = row["name"].translate(NAME_REPLACEMENTS)
        out[key] = row
    return out


def build_formula_variants() -> dict:
    """Compare all 42 cross-book same-name pairs between Shanghan and Jinkui without merging records."""
    shanghan = read_json(DATA / "formulas.json")
    jinkui = read_json(DATA / "jinkui_formulas.json")
    sh_by_id = {r["id"]: r for r in shanghan}
    jk_by_id = {r["id"]: r for r in jinkui}
    dup_report = audit()

    items = []
    for grp in dup_report["cross_book_groups"]:
        sh_id = next(x for x in grp["ids"] if x.startswith("shanghan:"))
        jk_id = next(x for x in grp["ids"] if x.startswith("jinkui:"))
        sh_row = sh_by_id[sh_id]
        jk_row = jk_by_id[jk_id]
        sh_ings = _ing_map(sh_row)
        jk_ings = _ing_map(jk_row)

        only_sh = [k for k in sh_ings if k not in jk_ings]
        only_jk = [k for k in jk_ings if k not in sh_ings]
        common = [k for k in sh_ings if k in jk_ings]
        dose_or_proc_diffs = []
        for k in common:
            s_i, j_i = sh_ings[k], jk_ings[k]
            s_dose = f"{s_i.get('dose', '')}{('·' + s_i['processing']) if s_i.get('processing') else ''}".strip()
            j_dose = f"{j_i.get('dose', '')}{('·' + j_i['processing']) if j_i.get('processing') else ''}".strip()
            if s_dose != j_dose:
                dose_or_proc_diffs.append({"herb": k, "shanghan": s_dose or "未注", "jinkui": j_dose or "未注"})

        sh_dec = (sh_row.get("decoction") or "").strip()
        jk_dec = (jk_row.get("decoction") or "").strip()
        decoction_same = sh_dec == jk_dec

        if grp["same_composition_and_dose"] and decoction_same:
            summary = f"《伤寒论》（{sh_row.get('six_meridian') or '伤寒篇'}）与《金匮要略》（{jk_row.get('chapter')}）药味剂量及煎法文字一致，但所治病位条文各具独立证据，分别保留互参。"
        elif grp["same_composition_and_dose"]:
            summary = f"两书药味与剂量相同，但煎服法字句或分服要求有别（《伤寒论》属{sh_row.get('six_meridian') or '六经'}，《金匮要略》见于「{jk_row.get('chapter')}」），保留双条对照。"
        else:
            diff_parts = []
            if only_sh or only_jk:
                diff_parts.append(f"药味异同（伤寒独见：{'、'.join(only_sh) or '无'}；金匮独见：{'、'.join(only_jk) or '无'}）")
            if dose_or_proc_diffs:
                diff_parts.append(f"剂量/炮制写法差异共 {len(dose_or_proc_diffs)} 味（如{dose_or_proc_diffs[0]['herb']}）")
            summary = f"同名异参方：{'；'.join(diff_parts)}。两书各自保留独立条文证据，不可简单去重合并。"

        items.append(
            {
                "normalized_name": grp["name"],
                "shanghan_id": sh_id,
                "jinkui_id": jk_id,
                "same_composition_and_dose": grp["same_composition_and_dose"],
                "decoction_same": decoction_same,
                "herb_diff": {"only_in_shanghan": only_sh, "only_in_jinkui": only_jk},
                "dose_or_processing_diffs": dose_or_proc_diffs,
                "shanghan_snapshot": {
                    "id": sh_id,
                    "name": sh_row["name"],
                    "book": "伤寒论",
                    "section": sh_row.get("six_meridian") or "",
                    "page_or_line": sh_row.get("source", {}).get("line") or sh_row.get("source", {}).get("page"),
                    "ingredients": sh_row.get("ingredients", []),
                    "decoction": sh_dec,
                    "indication": sh_row.get("indication", ""),
                },
                "jinkui_snapshot": {
                    "id": jk_id,
                    "name": jk_row["name"],
                    "book": "金匮要略",
                    "section": jk_row.get("chapter") or "",
                    "page_or_line": jk_row.get("source", {}).get("page"),
                    "ingredients": jk_row.get("ingredients", []),
                    "decoction": jk_dec,
                    "indication": jk_row.get("indication", ""),
                },
                "summary": summary,
            }
        )

    payload = {
        "total_groups": len(items),
        "exact_same_count": sum(1 for x in items if x["same_composition_and_dose"]),
        "different_count": sum(1 for x in items if not x["same_composition_and_dose"]),
        "items": items,
    }
    write_json(DATA / "formula_variants.json", payload)
    return payload


def _mod(
    idx: int,
    base: str,
    condition: str,
    add: list[str],
    remove: list[str],
    dose_adjust: list[str],
    target: str | None,
    rationale: str,
    boundary: str,
    book: str,
    page_ref: str,
    excerpt: str,
    evidence_status: str = "verified",
) -> dict:
    summary_parts = []
    if remove:
        summary_parts.append(f"去{'、'.join(remove)}")
    if add:
        summary_parts.append(f"加{'、'.join(add)}")
    if dose_adjust:
        summary_parts.append("；".join(dose_adjust))
    return {
        "id": f"mod-{idx:03d}",
        "base_formula_id": base,
        "base_formula_name": base.split(":", 1)[1],
        "condition": condition,
        "changes": {
            "add": add,
            "remove": remove,
            "dose_adjust": dose_adjust,
            "summary": "，".join(summary_parts) or "按条文重定剂量或主辅",
        },
        "target_formula_id": target,
        "target_formula_name": target.split(":", 1)[1] if target else None,
        "rationale": rationale,
        "boundary": boundary,
        "evidence_status": evidence_status,
        "source": {"book": book, "ref": page_ref, "excerpt": excerpt},
    }


