def resolve(name: str) -> tuple[str | None, str]:
    """返回 (本经或增补条目名, 状态)。状态：exact / alias / missing。"""
    if not name:
        return None, "missing"
    entry = ALIAS.get(name)
    if entry:
        return entry[0], "alias"
    return name, "exact"


def controversy_note(name: str) -> str:
    """若方中药名存在古今基原、炮制或同名争议，返回争议说明，否则返回空串。"""
    return CONTROVERSY_ALIASES.get(name or "", "")
