"""Read-only formula evidence extracted from the local classical corpus.

The evidence file is generated by scripts/extract_library_formula_evidence.py
from knowledge/knowledge.sqlite3. Every quote is an exact substring of a stored
page or text unit and keeps its locator and SHA256.
"""
from copy import deepcopy
from functools import lru_cache
import json
from pathlib import Path

from . import formula_engine, library_modifications

ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "library_evidence"
FORMAT = "nihaixia-library-formula-evidence"
COMPOSITION_FORMAT = "nihaixia-library-formula-compositions"
VERSION = 1
NOTICE = "库内原文检索证据，不表示该方适用于当前患者；引用可能受 OCR 质量影响，须回看原件。"


def _read(name: str) -> dict:
    path = DATA_DIR / name
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise ValueError(f"库内证据数据缺失：{name}") from exc
    except json.JSONDecodeError as exc:
        raise ValueError(f"库内证据数据格式错误：{name}") from exc


@lru_cache(maxsize=1)
def _data() -> dict:
    data = _read("formula_mentions.json")
    if (not isinstance(data, dict) or data.get("format") != FORMAT or data.get("version") != VERSION
            or not isinstance(data.get("formulas"), list) or not data["formulas"]):
        raise ValueError("库内证据数据格式或版本不兼容")
    seen = set()
    for item in data["formulas"]:
        if not isinstance(item, dict) or not item.get("formula_id") or not item.get("formula_name"):
            raise ValueError("库内证据条目缺少方剂 id 或名称")
        if item["formula_id"] in seen:
            raise ValueError(f"库内证据方剂 id 重复：{item['formula_id']}")
        seen.add(item["formula_id"])
        if not isinstance(item.get("evidence"), list):
            raise ValueError(f"库内证据条目格式无效：{item['formula_id']}")
        for evidence in item["evidence"]:
            if not isinstance(evidence, dict) or not evidence.get("quote") or not evidence.get("locator"):
                raise ValueError(f"库内证据缺少引文或定位：{item['formula_id']}")
    return data


@lru_cache(maxsize=1)
def _index() -> dict:
    return {item["formula_id"]: item for item in _data()["formulas"]}


@lru_cache(maxsize=1)
def _compositions() -> dict:
    data = _read("formula_compositions.json")
    if (not isinstance(data, dict) or data.get("format") != COMPOSITION_FORMAT or data.get("version") != VERSION
            or not isinstance(data.get("formulas"), list)):
        raise ValueError("库内方剂组成数据格式或版本不兼容")
    seen = set()
    for item in data["formulas"]:
        if not isinstance(item, dict) or not item.get("formula_id") or not isinstance(item.get("versions"), list):
            raise ValueError("库内方剂组成条目格式无效")
        if item["formula_id"] in seen:
            raise ValueError(f"库内方剂组成 id 重复：{item['formula_id']}")
        seen.add(item["formula_id"])
        for version in item["versions"]:
            if not isinstance(version, dict) or not version.get("block") or not isinstance(version.get("components"), list):
                raise ValueError(f"库内方剂组成版本格式无效：{item['formula_id']}")
    return data


@lru_cache(maxsize=1)
def _composition_index() -> dict:
    return {item["formula_id"]: item for item in _compositions()["formulas"]}


def all_formulas() -> list[dict]:
    return deepcopy(_data()["formulas"])


def clear_cache() -> None:
    _data.cache_clear()
    _index.cache_clear()
    _compositions.cache_clear()
    _composition_index.cache_clear()


def summary() -> dict:
    data = _data()
    return {
        "review_status": "library_source",
        "notice": NOTICE,
        **deepcopy(data.get("counts") or {}),
        "compositions": deepcopy(_compositions().get("counts") or {}),
        "source": deepcopy(data.get("source") or {}),
    }


def _formula_summary(formula_id: str, name: str) -> dict:
    formula = formula_engine.get_formula(formula_id) or {}
    return {
        "id": formula_id,
        "name": formula.get("name") or name,
        "syndrome": formula.get("syndrome", ""),
        "six_meridian": formula.get("six_meridian", ""),
        "components": deepcopy(formula.get("components", [])),
        "source_refs": deepcopy(formula.get("source_refs", [])),
    }


def get_formula(formula_id: str) -> dict | None:
    item = _index().get(str(formula_id))
    formula = formula_engine.get_formula(str(formula_id))
    if item is None and formula is None:
        return None
    versions = deepcopy((_composition_index().get(str(formula_id)) or {}).get("versions") or [])
    if item is None:
        return {
            "formula": _formula_summary(str(formula_id), formula.get("name", "")),
            "mention_count": 0,
            "document_count": 0,
            "documents": [],
            "evidence": [],
            "compositions": versions,
            "modifications": library_modifications.for_formula(str(formula_id)),
            "review_status": "library_source",
            "notice": "库内未检索到该方名的原文证据。",
        }
    result = {
        "formula": _formula_summary(item["formula_id"], item["formula_name"]),
        "mention_count": item.get("mention_count", 0),
        "document_count": item.get("document_count", 0),
        "documents": deepcopy(item.get("documents") or []),
        "evidence": deepcopy(item.get("evidence") or []),
        "compositions": versions,
        "modifications": library_modifications.for_formula(str(formula_id)),
        "review_status": "library_source",
        "notice": NOTICE,
    }
    return result


def search(query: str = "", limit: int = 30) -> dict:
    if not isinstance(query, str) or len(query) > 80:
        raise ValueError("搜索词过长")
    if type(limit) is not int or not 1 <= limit <= 100:
        raise ValueError("limit 须在 1 到 100 之间")
    term = query.strip()
    items = []
    for item in _data()["formulas"]:
        matched_quotes = []
        score = 0
        if not term:
            score = item.get("mention_count", 0)
        else:
            if term in item["formula_name"]:
                score += 100
            if term in " ".join(item.get("documents") or []):
                score += 10
            for evidence in item.get("evidence") or []:
                if term in evidence.get("quote", ""):
                    matched_quotes.append({
                        "source_title": evidence.get("source_title"),
                        "locator": evidence.get("locator"),
                        "quote": evidence.get("quote"),
                        "cue": evidence.get("cue"),
                    })
                    score += 5
                    if len(matched_quotes) >= 3:
                        break
            if not score:
                continue
        items.append({
            "formula_id": item["formula_id"],
            "formula_name": item["formula_name"],
            "mention_count": item.get("mention_count", 0),
            "document_count": item.get("document_count", 0),
            "matched_quotes": matched_quotes,
            "score": score,
        })
    items.sort(key=lambda item: (-item["score"], -item["mention_count"], item["formula_name"]))
    return {"items": items[:limit], "total": len(items), "review_status": "library_source", "notice": NOTICE}


def mount_library_evidence_routes(app, protected):
    from fastapi import HTTPException, Query

    @app.get("/api/library/evidence/summary", dependencies=protected)
    def library_evidence_summary():
        return summary()

    @app.get("/api/library/evidence/formulas/{formula_id}", dependencies=protected)
    def library_formula_evidence(formula_id: str):
        item = get_formula(formula_id)
        if item is None:
            raise HTTPException(404, "未找到该方剂")
        return item

    @app.get("/api/library/evidence/search", dependencies=protected)
    def library_evidence_search(q: str = Query(default="", max_length=80),
                                limit: int = Query(default=30, ge=1, le=100)):
        return search(q, limit)
